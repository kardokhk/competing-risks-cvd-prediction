#!/usr/bin/env python
"""P2-A step 00. Missingness report for the version 2 re-analysis.

Quantifies what complete-case analysis threw away and why it is not ignorable,
which is the justification for making multiple imputation primary.

Writes results/metrics_v2/missingness_report.md and
results/metrics_v2/missingness_tables/*.csv.

Run:
    ${ENV_PREFIX}/crcvd-py/bin/python src/v2/00_missingness.py
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
SPEC = json.loads((ROOT / "src" / "v2" / "feature_spec.json").read_text())
PRED = SPEC["primary_features"]
OUT = ROOT / "results" / "metrics_v2"
TAB = OUT / "missingness_tables"
SEED = SPEC["seed"]


def load() -> pd.DataFrame:
    d = pd.read_parquet(ROOT / "data" / "processed" / "analytic.parquet")
    # time: exam-based where observed, interview-based otherwise (see PREDICTION_FORMAT.md s.2)
    d["time"] = d["followup_years_exm"].where(d["followup_years_exm"].notna(),
                                              d["followup_years_int"])
    d["time_source"] = np.where(d["followup_years_exm"].notna(), "exm", "int")
    d["R_miss_any"] = d[PRED].isna().any(axis=1).astype(int)
    d["n_miss"] = d[PRED].isna().sum(axis=1)
    return d


def aj_cif_point(time, event, t=10.0, cause=1):
    """Exact Aalen-Johansen CIF for `cause` at time t. No jitter, ties handled exactly.

    CIF_j(t) = sum_{t_i <= t} S(t_i-) * d_{j,i} / n_i, with S the Kaplan-Meier of
    survival free of any event. Vectorised; used inside the bootstrap.
    """
    time = np.asarray(time, float)
    event = np.asarray(event, int)
    ut, inv = np.unique(time, return_inverse=True)
    n_ev = np.bincount(inv, minlength=len(ut))
    d_any = np.bincount(inv, weights=(event > 0).astype(float), minlength=len(ut))
    d_j = np.bincount(inv, weights=(event == cause).astype(float), minlength=len(ut))
    at_risk = len(time) - np.concatenate(([0.0], np.cumsum(n_ev)[:-1]))
    haz = np.divide(d_any, at_risk, out=np.zeros_like(d_any), where=at_risk > 0)
    s_prev = np.concatenate(([1.0], np.cumprod(1.0 - haz)[:-1]))
    inc = s_prev * np.divide(d_j, at_risk, out=np.zeros_like(d_j), where=at_risk > 0)
    cif = np.cumsum(inc)
    k = np.searchsorted(ut, t, side="right") - 1
    return float(cif[k]) if k >= 0 else 0.0


def aj_cif(time, event, t=10.0, cause=1, seed=SEED, nboot=500):
    """AJ CIF point estimate with a nonparametric percentile bootstrap 95% CI."""
    time = np.asarray(time, float)
    event = np.asarray(event, int)
    point = aj_cif_point(time, event, t=t, cause=cause)
    rng = np.random.default_rng(seed)
    n = len(time)
    bs = np.empty(nboot)
    for b in range(nboot):
        idx = rng.integers(0, n, n)
        bs[b] = aj_cif_point(time[idx], event[idx], t=t, cause=cause)
    return point, float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def prop_ci(k, n):
    """Wilson 95% interval for a proportion."""
    if n == 0:
        return (np.nan, np.nan, np.nan)
    p = k / n
    z = 1.959963984540054
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0.0, c - h), min(1.0, c + h)


def mean_diff_ci(a, b):
    """Welch mean difference (a - b) with a 95% CI."""
    a = np.asarray(a, float); b = np.asarray(b, float)
    a = a[np.isfinite(a)]; b = b[np.isfinite(b)]
    d = a.mean() - b.mean()
    se = np.sqrt(a.var(ddof=1) / len(a) + b.var(ddof=1) / len(b))
    df = se**4 / (
        (a.var(ddof=1) / len(a)) ** 2 / (len(a) - 1)
        + (b.var(ddof=1) / len(b)) ** 2 / (len(b) - 1)
    )
    q = stats.t.ppf(0.975, df)
    return d, d - q * se, d + q * se, df


def main() -> None:
    TAB.mkdir(parents=True, exist_ok=True)
    d = load()
    n = len(d)
    L = []
    W = L.append

    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                                capture_output=True, text=True).stdout.strip()
    except Exception:
        commit = "unknown"

    W("# Missingness in the analytic cohort, and why complete-case analysis is not defensible here")
    W("")
    W(f"Generated by `src/v2/00_missingness.py` on {pd.Timestamp.today().date()} "
      f"(repo commit `{commit or 'unknown'}`, seed {SEED}).")
    W("")
    W(f"Cohort: `data/processed/analytic.parquet`, N = {n:,} mortality-eligible respondents "
      "aged 30-79.")
    W("")

    # ---------------------------------------------------------------- 1
    W("## 1. Missingness by predictor")
    W("")
    rows = []
    for v in PRED:
        k = int(d[v].isna().sum())
        p, lo, hi = prop_ci(k, n)
        rows.append({"variable": v, "n_missing": k, "pct_missing": 100 * p,
                     "pct_lo": 100 * lo, "pct_hi": 100 * hi})
    t1 = pd.DataFrame(rows).sort_values("n_missing", ascending=False)
    t1.to_csv(TAB / "missing_by_predictor.csv", index=False)
    W("| predictor | n missing | % missing (95% CI) |")
    W("|---|---|---|")
    for _, r in t1.iterrows():
        W(f"| `{r.variable}` | {int(r.n_missing):,} | {r.pct_missing:.2f} "
          f"({r.pct_lo:.2f} to {r.pct_hi:.2f}) |")
    W("")
    complete = int((d.n_miss == 0).sum())
    W(f"Rows complete on all 11 predictors: **{complete:,}** ({100*complete/n:.2f}%). "
      f"Rows with at least one predictor missing: **{n-complete:,}** ({100*(n-complete)/n:.2f}%).")
    W("")
    W("The six binary and demographic predictors (`age`, `sex`, `antihtn`, `statin`, `diabetes`, "
      "`smoke_current`) are complete by construction: NHANES questionnaire skip patterns are coded "
      "to 0 and `diabetes` combines a self-report with HbA1c, so a row is missing only if both are "
      "unknown. All loss comes from the five MEC-derived measurements.")
    W("")

    # ---------------------------------------------------------------- 2
    W("## 2. Which predictors drive the loss")
    W("")
    miss = d[PRED].isna()
    rows = []
    for v in PRED:
        k = int(miss[v].sum())
        if k == 0:
            continue
        only = int((miss[v] & (d.n_miss == 1)).sum())
        rows.append({"variable": v, "n_missing": k,
                     "n_sole_cause_of_exclusion": only,
                     "pct_of_excluded_rows": 100 * k / (n - complete)})
    t2 = pd.DataFrame(rows).sort_values("n_missing", ascending=False)
    t2.to_csv(TAB / "loss_drivers.csv", index=False)
    W("| predictor | n missing | n rows where it is the *only* missing predictor | % of the "
      f"{n-complete:,} excluded rows in which it is missing |")
    W("|---|---|---|---|")
    for _, r in t2.iterrows():
        W(f"| `{r.variable}` | {int(r.n_missing):,} | {int(r.n_sole_cause_of_exclusion):,} | "
          f"{r.pct_of_excluded_rows:.1f} |")
    W("")
    W("### Missingness patterns")
    W("")
    pat = (miss[PRED].astype(int).astype(str).agg("".join, axis=1))
    vc = pat.value_counts().head(12)
    labels = []
    for code, cnt in vc.items():
        vs = [p for p, c in zip(PRED, code) if c == "1"]
        labels.append({"pattern": ", ".join(vs) if vs else "(complete)",
                       "n": int(cnt), "pct": 100 * cnt / n})
    t2b = pd.DataFrame(labels)
    t2b.to_csv(TAB / "missing_patterns.csv", index=False)
    W("| missing set | n | % of cohort |")
    W("|---|---|---|")
    for _, r in t2b.iterrows():
        W(f"| {r['pattern']} | {int(r.n):,} | {r.pct:.2f} |")
    W("")
    nonmec = int(d["followup_years_exm"].isna().sum())
    W(f"The single largest incomplete pattern is the block of five MEC measurements missing "
      f"together. It is the {nonmec:,} respondents who were interviewed but never attended the "
      "mobile examination centre, plus a small number of partial-examination respondents. Their "
      "missingness is a structural consequence of the survey protocol, not of the measurement.")
    W("")

    # ---------------------------------------------------------------- 3
    W("## 3. Missingness is outcome-dependent")
    W("")
    ct = pd.crosstab(d.R_miss_any, d.event)
    ct.to_csv(TAB / "missing_by_event.csv")
    chi2, pval, dof, _ = stats.chi2_contingency(ct.values)
    W("Observed event distribution by whether the row has any missing predictor:")
    W("")
    W("| any predictor missing | n | censored | CVD death | competing death | CVD death % (95% CI) "
      "| competing death % (95% CI) |")
    W("|---|---|---|---|---|---|---|")
    for r_ in [0, 1]:
        sub = d[d.R_miss_any == r_]
        c0 = int((sub.event == 0).sum()); c1 = int((sub.event == 1).sum())
        c2 = int((sub.event == 2).sum())
        p1, l1, h1 = prop_ci(c1, len(sub)); p2, l2, h2 = prop_ci(c2, len(sub))
        W(f"| {'yes' if r_ else 'no'} | {len(sub):,} | {c0:,} | {c1:,} | {c2:,} | "
          f"{100*p1:.2f} ({100*l1:.2f} to {100*h1:.2f}) | "
          f"{100*p2:.2f} ({100*l2:.2f} to {100*h2:.2f}) |")
    W("")
    pstr = "< 0.001" if pval < 0.001 else f"= {pval:.2f}"
    W(f"Chi-square test of independence between missingness and the three-level event indicator: "
      f"chi-square = {chi2:.1f} on {dof} df, *P* {pstr}.")
    W("")
    # risk differences with CI
    a = d[d.R_miss_any == 1]; b = d[d.R_miss_any == 0]
    for cause, name in [(1, "CVD death"), (2, "competing death")]:
        ka, na_ = int((a.event == cause).sum()), len(a)
        kb, nb = int((b.event == cause).sum()), len(b)
        pa, pb = ka / na_, kb / nb
        se = np.sqrt(pa * (1 - pa) / na_ + pb * (1 - pb) / nb)
        diff = pa - pb
        W(f"- Crude risk difference for observed {name}, incomplete minus complete: "
          f"{100*diff:+.2f} percentage points "
          f"(95% CI {100*(diff-1.96*se):+.2f} to {100*(diff+1.96*se):+.2f}).")
    W("")
    W("Crude proportions confound follow-up length, so the comparison that matters is the "
      "competing-risk cumulative incidence at a fixed horizon.")
    W("")

    # ---------------------------------------------------------------- 4
    W("## 4. The quantity the complete-case analysis gets wrong")
    W("")
    rows = []
    for t in (5.0, 10.0):
        for lab, sub in [("full cohort", d), ("complete cases", d[d.R_miss_any == 0]),
                         ("incomplete cases", d[d.R_miss_any == 1])]:
            c, lo, hi = aj_cif(sub.time, sub.event, t=t, cause=1)
            c2, _, _ = aj_cif(sub.time, sub.event, t=t, cause=2)
            rows.append({"horizon_y": t, "set": lab, "n": len(sub),
                         "cif_cvd": c, "cif_cvd_lo": lo, "cif_cvd_hi": hi,
                         "cif_competing": c2})
    t4 = pd.DataFrame(rows)
    t4.to_csv(TAB / "observed_cif_by_completeness.csv", index=False)
    W("Aalen-Johansen cumulative incidence, unweighted:")
    W("")
    W("| horizon | set | n | CVD CIF % (95% CI) | competing-death CIF % |")
    W("|---|---|---|---|---|")
    for _, r in t4.iterrows():
        W(f"| {r.horizon_y:.0f} y | {r['set']} | {int(r.n):,} | {100*r.cif_cvd:.3f} "
          f"({100*r.cif_cvd_lo:.3f} to {100*r.cif_cvd_hi:.3f}) | {100*r.cif_competing:.3f} |")
    W("")
    f10 = t4[(t4.horizon_y == 10) & (t4["set"] == "full cohort")].cif_cvd.iloc[0]
    c10 = t4[(t4.horizon_y == 10) & (t4["set"] == "complete cases")].cif_cvd.iloc[0]
    W(f"At 10 y the complete-case CVD cumulative incidence is {100*c10:.3f}% against "
      f"{100*f10:.3f}% in the full cohort, a relative shortfall of "
      f"{100*(f10-c10)/f10:.1f}%.")
    W("")
    W("This is the number that makes complete-case analysis untenable as the primary analysis. "
      "Every model in the benchmark is calibrated against an observed cumulative incidence, and "
      "E/O is a ratio whose denominator is exactly this quantity. A denominator that is low by "
      "this much moves every E/O, and it moves the naive and competing-risk arms by different "
      "amounts because the competing-death incidence is also displaced.")
    W("")

    # ---------------------------------------------------------------- 5
    W("## 5. Missingness by age, cycle and design")
    W("")
    dm, lo, hi, dfree = mean_diff_ci(a.age, b.age)
    W(f"Mean age, incomplete minus complete: {dm:+.2f} y (95% CI {lo:+.2f} to {hi:+.2f}, "
      f"Welch df {dfree:.0f}). Incomplete rows mean {a.age.mean():.1f} y (SD {a.age.std():.1f}), "
      f"complete rows mean {b.age.mean():.1f} y (SD {b.age.std():.1f}).")
    W("")
    grp = d.groupby("cycle").apply(
        lambda g: pd.Series({"n": len(g), "n_miss_any": int(g.R_miss_any.sum()),
                             "pct_miss_any": 100 * g.R_miss_any.mean(),
                             "mean_age": g.age.mean(),
                             "pct_cvd_obs": 100 * (g.event == 1).mean()}),
        include_groups=False).reset_index()
    grp.to_csv(TAB / "missing_by_cycle.csv", index=False)
    W("| cycle | n | n with any missing | % missing | mean age | observed CVD death % |")
    W("|---|---|---|---|---|---|")
    for _, r in grp.iterrows():
        W(f"| {r.cycle} | {int(r.n):,} | {int(r.n_miss_any):,} | {r.pct_miss_any:.1f} | "
          f"{r.mean_age:.1f} | {r.pct_cvd_obs:.2f} |")
    W("")
    ct2 = pd.crosstab(d.cycle, d.R_miss_any)
    chi2c, pc, dofc, _ = stats.chi2_contingency(ct2.values)
    pcs = "< 0.001" if pc < 0.001 else f"= {pc:.2f}"
    W(f"Missingness varies by cycle: chi-square = {chi2c:.1f} on {dofc} df, *P* {pcs}. "
      "Cycle is therefore included in the imputation model, and any pooled analysis that "
      "ignores it inherits a cycle-by-missingness interaction.")
    W("")
    # by split
    def split_of(y):
        if y in SPEC["train_startyrs"]:
            return "train (1999-2006)"
        if y in SPEC["test_startyrs"]:
            return "test (2007-2010)"
        return "holdout_later (2011-2018)"
    d["_split"] = d.cycle_startyr.map(split_of)
    sp = d.groupby("_split").agg(n=("SEQN", "size"), pct_miss=("R_miss_any", "mean")).reset_index()
    sp["pct_miss"] *= 100
    sp.to_csv(TAB / "missing_by_split.csv", index=False)
    W("| temporal split | n | % with any predictor missing |")
    W("|---|---|---|")
    for _, r in sp.iterrows():
        W(f"| {r._split} | {int(r.n):,} | {r.pct_miss:.1f} |")
    W("")

    # ---------------------------------------------------------------- 6
    W("## 6. Censoring is administrative and varies steeply by cycle")
    W("")
    rows = []
    for cyc, g in d.groupby("cycle"):
        for t in (5.0, 10.0, 15.0):
            at_risk = float(((g.time >= t) | (g.event > 0) & (g.time < t)).mean())
            adm = float((g.event == 0).mean())
            rows.append({"cycle": cyc, "horizon_y": t,
                         "pct_censored_before_horizon": 100 * float(((g.event == 0) & (g.time < t)).mean()),
                         "pct_followed_to_horizon_or_event": 100 * at_risk,
                         "pct_censored_overall": 100 * adm})
    t6 = pd.DataFrame(rows)
    t6.to_csv(TAB / "censoring_by_cycle.csv", index=False)
    W("Percentage of each cycle administratively censored before the horizon (mortality linkage "
      "ends 31 Dec 2019):")
    W("")
    W("| cycle | censored before 5 y | before 10 y | before 15 y |")
    W("|---|---|---|---|")
    for cyc in grp.cycle:
        s = t6[t6.cycle == cyc].set_index("horizon_y")
        W(f"| {cyc} | {s.loc[5.0,'pct_censored_before_horizon']:.1f}% | "
          f"{s.loc[10.0,'pct_censored_before_horizon']:.1f}% | "
          f"{s.loc[15.0,'pct_censored_before_horizon']:.1f}% |")
    W("")
    W("Censoring before 10 y ranges from 0% in the earliest cycles to essentially the whole "
      "cycle in the latest, and it is administrative, driven entirely by calendar time between "
      "the examination and the end of linkage. A single marginal Kaplan-Meier censoring "
      "distribution is therefore badly misspecified: it averages cycles whose censoring hazards "
      "have no overlap. All inverse-probability-of-censoring weights in this re-analysis are "
      "estimated **within cycle**, and the effect of that change is reported in "
      "`results/metrics_v2/SUMMARY.md`.")
    W("")

    W("## 7. Consequence for the analysis")
    W("")
    W("1. Multiple imputation is the primary analysis. Complete-case results are retained only as "
      "a sensitivity analysis and are labelled as such.")
    W("2. The imputation model is outcome-aware: it contains the event indicators and the "
      "cause-specific Nelson-Aalen cumulative hazards, not the follow-up time itself.")
    W("3. Cycle enters the imputation model, and censoring weights are estimated within cycle.")
    W("4. Every evaluation table reports the at-risk fraction at the horizon, because a stratum "
      "can be nominally large and still contribute almost no information at 15 y.")
    W("")

    (OUT / "missingness_report.md").write_text("\n".join(L) + "\n")
    print(f"wrote {OUT/'missingness_report.md'} ({len(L)} lines)")
    print(f"wrote {len(list(TAB.glob('*.csv')))} tables to {TAB}")


if __name__ == "__main__":
    sys.exit(main())
